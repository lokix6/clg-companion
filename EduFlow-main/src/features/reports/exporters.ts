import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import * as XLSX from "xlsx";
import Papa from "papaparse";
import {
  BRAND,
  TAGLINE,
  collegeName,
  formatFiltersForDisplay,
  generatedByLabel,
  nowStamp,
  type ReportContext,
} from "./branding";
import { REPORT_LOGO_PNG } from "./logo-data";

export type ExportFormat = "pdf" | "xlsx" | "csv";

export type ReportColumn = {
  key: string;
  label: string;
  width?: number;
  align?: "left" | "right" | "center";
  format?: (v: unknown, row: Record<string, unknown>) => string;
};

export type ReportPayload = {
  title: string;
  kind: string;
  columns: ReportColumn[];
  rows: Record<string, unknown>[];
  summary?: { label: string; value: string | number }[];
};

function cellText(col: ReportColumn, row: Record<string, unknown>): string {
  const raw = row[col.key];
  if (col.format) return col.format(raw, row);
  if (raw == null) return "—";
  if (raw instanceof Date) return raw.toLocaleDateString();
  return String(raw);
}

function slug(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

export function fileName(payload: ReportPayload, format: ExportFormat): string {
  const stamp = new Date().toISOString().slice(0, 10);
  return `${slug(payload.title)}-${stamp}.${format}`;
}

// -------------------------- PDF --------------------------

export function exportPdf(payload: ReportPayload, ctx: ReportContext): void {
  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  const w = doc.internal.pageSize.getWidth();

  // Header band
  doc.setFillColor(88, 80, 236);
  doc.rect(0, 0, w, 24, "F");
  // Brand logo
  doc.setFillColor(255, 255, 255);
  doc.circle(18, 12, 7, "F");
  try {
    doc.addImage(REPORT_LOGO_PNG, "PNG", 12, 6, 12, 12);
  } catch {
    /* logo optional */
  }

  doc.setTextColor(255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text(collegeName(ctx.profile), 30, 11);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.text(`${BRAND} • ${TAGLINE}`, 30, 17);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.text(payload.title, w - 14, 14, { align: "right" });

  // Meta
  doc.setTextColor(30);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  let y = 32;
  doc.text(`Generated by: ${generatedByLabel(ctx.profile)} (${ctx.role})`, 14, y);
  doc.text(`Generated: ${nowStamp()}`, w - 14, y, { align: "right" });
  y += 5;

  const flines = formatFiltersForDisplay(ctx.filters, ctx.filterLabels);
  if (flines.length) {
    doc.setTextColor(90);
    doc.text(`Filters — ${flines.join("  |  ")}`, 14, y);
    y += 5;
  }

  if (payload.summary && payload.summary.length) {
    doc.setTextColor(30);
    doc.setFont("helvetica", "bold");
    doc.text("Summary", 14, y + 2);
    doc.setFont("helvetica", "normal");
    const summaryText = payload.summary.map((s) => `${s.label}: ${s.value}`).join("   |   ");
    doc.text(summaryText, 14, y + 7);
    y += 12;
  }

  doc.setDrawColor(220);
  doc.line(14, y, w - 14, y);
  y += 2;

  if (payload.rows.length === 0) {
    doc.setFont("helvetica", "italic");
    doc.setTextColor(120);
    doc.text("No data available for the selected filters.", 14, y + 8);
  } else {
    const head = [payload.columns.map((c) => c.label)];
    const body = payload.rows.map((r) => payload.columns.map((c) => cellText(c, r)));
    autoTable(doc, {
      startY: y + 4,
      head,
      body,
      theme: "grid",
      styles: { fontSize: 8, cellPadding: 2.5, overflow: "linebreak" },
      headStyles: { fillColor: [88, 80, 236], textColor: 255 },
      alternateRowStyles: { fillColor: [245, 246, 251] },
      margin: { left: 14, right: 14 },
      didDrawPage: () => {
        const h = doc.internal.pageSize.getHeight();
        doc.setFontSize(8);
        doc.setTextColor(140);
        doc.text(`${BRAND} • ${collegeName(ctx.profile)}`, 14, h - 8);
      },
    });
  }

  // Finalize page numbers with correct total
  const total = doc.getNumberOfPages();
  const h = doc.internal.pageSize.getHeight();
  for (let i = 1; i <= total; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(140);
    doc.text(`Page ${i} of ${total}`, w - 14, h - 8, { align: "right" });
  }

  doc.save(fileName(payload, "pdf"));
}

// -------------------------- XLSX --------------------------

export function exportXlsx(payload: ReportPayload, ctx: ReportContext): void {
  const wb = XLSX.utils.book_new();
  const filterLines = formatFiltersForDisplay(ctx.filters, ctx.filterLabels);
  const meta: (string | number)[][] = [
    [collegeName(ctx.profile)],
    [payload.title],
    [`Generated by: ${generatedByLabel(ctx.profile)} (${ctx.role})`],
    [`Generated at: ${nowStamp()}`],
    [`Filters: ${filterLines.join(" | ") || "None"}`],
    [],
  ];
  if (payload.summary?.length) {
    meta.push(["Summary"]);
    for (const s of payload.summary) meta.push([s.label, s.value]);
    meta.push([]);
  }
  meta.push(payload.columns.map((c) => c.label));
  for (const r of payload.rows) meta.push(payload.columns.map((c) => cellText(c, r)));

  const ws = XLSX.utils.aoa_to_sheet(meta);
  ws["!cols"] = payload.columns.map((c) => ({ wch: Math.max(12, (c.label.length + 2) | 0, c.width ?? 0) }));
  XLSX.utils.book_append_sheet(wb, ws, "Report");
  XLSX.writeFile(wb, fileName(payload, "xlsx"));
}

// -------------------------- CSV --------------------------

export function exportCsv(payload: ReportPayload, ctx: ReportContext): void {
  const filterLines = formatFiltersForDisplay(ctx.filters, ctx.filterLabels);
  const header = [
    `# ${collegeName(ctx.profile)} — ${payload.title}`,
    `# Generated by: ${generatedByLabel(ctx.profile)} (${ctx.role})`,
    `# Generated at: ${nowStamp()}`,
    `# Filters: ${filterLines.join(" | ") || "None"}`,
    "",
  ].join("\n");
  const csv = Papa.unparse({
    fields: payload.columns.map((c) => c.label),
    data: payload.rows.map((r) => payload.columns.map((c) => cellText(c, r))),
  });
  const blob = new Blob([header + "\n" + csv], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = fileName(payload, "csv");
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

export function runExport(
  format: ExportFormat,
  payload: ReportPayload,
  ctx: ReportContext,
): void {
  if (format === "pdf") exportPdf(payload, ctx);
  else if (format === "xlsx") exportXlsx(payload, ctx);
  else exportCsv(payload, ctx);
}
